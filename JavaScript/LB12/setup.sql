begin;
-- Створюємо таблицю фотопроєктів.
create table if not exists public.photo_projects (
  -- Номер запису створюється автоматично.
  id bigint generated by default as identity primary key,
  -- Обов’язкові дані проєкту.
  title text not null,
  client text not null,
  category text not null,
  -- Дата додавання встановлюється автоматично.
  created_at timestamptz not null default now(),
  -- Назва повинна містити від 1 до 150 символів.
  constraint photo_projects_title_length
    check (char_length(trim(title)) between 1 and 150),
  -- Перевіряємо довжину назви замовника.
  constraint photo_projects_client_length
    check (char_length(trim(client)) between 1 and 150),
  -- Дозволені три напрями зйомки, як у курсовій.
  constraint photo_projects_category
    check (category in ('Портретна зйомка', 'Зйомка подій', 'Комерційна зйомка'))
);

-- Вмикаємо правила доступу до рядків.
alter table public.photo_projects enable row level security;

-- Дозволяємо відвідувачам читати каталог.
grant select on table public.photo_projects to anon;

-- Додавати можна лише ці три поля.
grant insert (title, client, category)
on table public.photo_projects
to anon;

-- Правило читання навчальних записів.
create policy "Public can read photo projects"
on public.photo_projects
for select
to anon
using (true);

-- Правило додавання навчальних записів.
create policy "Public can add photo projects"
on public.photo_projects
for insert
to anon
with check (true);

-- Додаємо п’ять вигаданих тестових проєктів.
insert into public.photo_projects (title, client, category)
values
  ('Студійний портрет', 'Навчальна творча команда', 'Портретна зйомка'),
  ('Реклама кави', 'Навчальна кав’ярня', 'Комерційна зйомка'),
  ('Фестиваль кольорів', 'Навчальна фотостудія', 'Зйомка подій'),
  ('Каталог одягу', 'Навчальний бренд одягу', 'Комерційна зйомка'),
  ('Щирість без масок', 'Навчальна творча група', 'Портретна зйомка');

-- Зберігаємо виконані зміни.
commit;

-- Перевіряємо RLS, права доступу та кількість записів.
select
  (select relrowsecurity from pg_class
    where oid = 'public.photo_projects'::regclass) as rls_enabled,
  has_table_privilege('anon', 'public.photo_projects', 'SELECT') as can_read,
  has_column_privilege('anon', 'public.photo_projects', 'title', 'INSERT') as can_add_title,
  has_column_privilege('anon', 'public.photo_projects', 'client', 'INSERT') as can_add_client,
  has_column_privilege('anon', 'public.photo_projects', 'category', 'INSERT') as can_add_category,
  (select count(*) from public.photo_projects) as records_count;
